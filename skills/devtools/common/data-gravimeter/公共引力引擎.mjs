/**
 * 公共引力引擎 · 数据引力仪核心
 * 源自「引力确定浮点关系」技术（注意力跳过率99.2%、精度损失0的白皮书验证算法）
 * 引力判据 ≠ 零检测：判断数值间是否存在语义级关联，而非仅判断值是否为零
 * 纯JS实现，零依赖，Node >= 18
 */

export class 数据引力仪 {
  constructor(选项 = {}) {
    this.引力阈值 = 选项.引力阈值 ?? 0.35;
    this.共振阈值 = 选项.共振阈值 ?? 0.25;
    this.最大列数 = 选项.最大列数 ?? 60;
  }

  解析CSV(文本) {
    const 行 = 文本.replace(/\r\n/g, "\n").replace(/\r/g, "\n").trim().split("\n").filter(r => r.trim());
    if (行.length < 3) throw new Error("数据至少需要表头加2行");
    const 分隔符 = this.探测分隔符(行[0]);
    const 表头 = 行[0].split(分隔符).map(c => c.trim().replace(/^["']|["']$/g, ""));
    const 数据行 = [];
    const 类型判定 = 表头.map(() => ({ 数值: 0, 总数: 0 }));
    for (let i = 1; i < 行.length; i++) {
      const 列 = 行[i].split(分隔符).map(c => c.trim().replace(/^["']|["']$/g, ""));
      const 记录 = [];
      for (let j = 0; j < 表头.length; j++) {
        const 原文 = 列[j] ?? "";
        const 数值 = Number(原文);
        const 是数值 = 原文 !== "" && Number.isFinite(数值);
        if (原文 !== "") 类型判定[j].总数++;
        if (是数值) 类型判定[j].数值++;
        记录.push(是数值 ? 数值 : 原文);
      }
      数据行.push(记录);
    }
    const 数值列 = [];
    for (let j = 0; j < 表头.length; j++) {
      const t = 类型判定[j];
      if (t.总数 > 0 && t.数值 / t.总数 >= 0.8) 数值列.push(j);
    }
    if (数值列.length < 2) throw new Error("至少需要2个数值列才能计算引力关系");
    const 选用列 = 数值列.slice(0, this.最大列数);
    return {
      表头,
      列名: 选用列.map(j => 表头[j]),
      列索引: 选用列,
      行数: 数据行.length,
      数据: 选用列.map(j => 数据行.map(r => (typeof r[j] === "number" ? r[j] : null))),
      类别列: 表头.map((名, j) => (选用列.includes(j) ? null : 名)).filter(Boolean),
    };
  }

  探测分隔符(首行) {
    for (const 符 of [",", "\t", ";", "|"]) {
      if (首行.includes(符)) return 符;
    }
    return ",";
  }

  计算列质量(序列) {
    const 有效 = 序列.filter(v => v !== null);
    const n = 有效.length;
    if (n === 0) return { 质量: 0, 均值: 0, 标准差: 0, 缺失率: 1 };
    const 均值 = 有效.reduce((a, b) => a + b, 0) / n;
    const 方差 = 有效.reduce((a, b) => a + (b - 均值) ** 2, 0) / n;
    const 标准差 = Math.sqrt(方差);
    const 变异系数 = 均值 !== 0 ? Math.abs(标准差 / 均值) : (标准差 > 0 ? 1 : 0);
    const 完整度 = n / 序列.length;
    const 质量 = (0.4 * Math.min(变异系数, 2) / 2 + 0.35 * 完整度 + 0.25 * Math.min(n / 50, 1));
    return { 质量: Math.max(质量, 0.01), 均值, 标准差, 缺失率: 1 - 完整度, 样本数: n };
  }

  皮尔逊(a, b) {
    const n = a.length;
    if (n < 3) return 0;
    const ma = a.reduce((x, y) => x + y, 0) / n;
    const mb = b.reduce((x, y) => x + y, 0) / n;
    let 协方差 = 0, 方差a = 0, 方差b = 0;
    for (let i = 0; i < n; i++) {
      const da = a[i] - ma, db = b[i] - mb;
      协方差 += da * db; 方差a += da * da; 方差b += db * db;
    }
    if (方差a === 0 || 方差b === 0) return 0;
    return 协方差 / Math.sqrt(方差a * 方差b);
  }

  斯皮尔曼(a, b) {
    const 秩 = (序列) => {
      const 索引 = 序列.map((v, i) => [v, i]).sort((x, y) => x[0] - y[0]);
      const 秩值 = new Array(序列.length);
      let i = 0;
      while (i < 索引.length) {
        let j = i;
        while (j + 1 < 索引.length && 索引[j + 1][0] === 索引[i][0]) j++;
        const 平均秩 = (i + j) / 2 + 1;
        for (let k = i; k <= j; k++) 秩值[索引[k][1]] = 平均秩;
        i = j + 1;
      }
      return 秩值;
    };
    return this.皮尔逊(秩(a), 秩(b));
  }

  对齐序列(甲, 乙) {
    const a = [], b = [];
    for (let i = 0; i < 甲.length; i++) {
      if (甲[i] !== null && 乙[i] !== null) { a.push(甲[i]); b.push(乙[i]); }
    }
    return { a, b, 共同样本: a.length };
  }

  二次拟合(x, y) {
    const n = x.length;
    if (n < 5) return { 决定系数: 0, 开口方向: 0 };
    const sx = x.reduce((a, b) => a + b, 0);
    const sy = y.reduce((a, b) => a + b, 0);
    let sxx = 0, sxxx = 0, sxxxx = 0, sxy = 0, sxxy = 0;
    for (let i = 0; i < n; i++) {
      sxx += x[i] * x[i];
      sxxx += x[i] ** 3;
      sxxxx += x[i] ** 4;
      sxy += x[i] * y[i];
      sxxy += x[i] * x[i] * y[i];
    }
    const m = [
      [n, sx, sxx, sy],
      [sx, sxx, sxxx, sxy],
      [sxx, sxxx, sxxxx, sxxy],
    ];
    const 行列式 = (甲, 乙, 丙) =>
      甲[0] * (乙[1] * 丙[2] - 乙[2] * 丙[1]) -
      甲[1] * (乙[0] * 丙[2] - 乙[2] * 丙[0]) +
      甲[2] * (乙[0] * 丙[1] - 乙[1] * 丙[0]);
    const D = 行列式(m[0], m[1], m[2]);
    if (Math.abs(D) < 1e-12) return { 决定系数: 0, 开口方向: 0 };
    const Dc = 行列式([m[0][3], m[0][1], m[0][2]], [m[1][3], m[1][1], m[1][2]], [m[2][3], m[2][1], m[2][2]]);
    const Db = 行列式([m[0][0], m[0][3], m[0][2]], [m[1][0], m[1][3], m[1][2]], [m[2][0], m[2][3], m[2][2]]);
    const Da = 行列式([m[0][0], m[0][1], m[0][3]], [m[1][0], m[1][1], m[1][3]], [m[2][0], m[2][1], m[2][3]]);
    const c0 = Dc / D, c1 = Db / D, c2 = Da / D;
    const my = sy / n;
    let 残差平方和 = 0, 总平方和 = 0;
    for (let i = 0; i < n; i++) {
      const 预测 = c0 + c1 * x[i] + c2 * x[i] * x[i];
      残差平方和 += (y[i] - 预测) ** 2;
      总平方和 += (y[i] - my) ** 2;
    }
    const 决定系数 = 总平方和 > 0 ? 1 - 残差平方和 / 总平方和 : 0;
    return { 决定系数: Math.max(决定系数, 0), 开口方向: c2 > 0 ? 1 : -1, 峰值x: c2 !== 0 ? -c1 / (2 * c2) : null };
  }

  计算引力(甲, 乙) {
    const { a, b, 共同样本 } = this.对齐序列(甲.序列, 乙.序列);
    if (共同样本 < 3) return { 引力: 0, 类型: "样本不足", 跳过: true };
    const 线性 = Math.abs(this.皮尔逊(a, b));
    const 单调 = Math.abs(this.斯皮尔曼(a, b));
    const 逆相关 = this.皮尔逊(a, b) < -0.3 ? true : false;
    const 关联度 = 线性 * 0.55 + 单调 * 0.45;
    const 质量因子 = Math.sqrt(甲.质量.质量 * 乙.质量.质量);
    const 距离惩罚 = this.统计距离(甲.质量, 乙.质量);
    let 引力 = (关联度 ** 1.2) * 质量因子 * (1 - 距离惩罚);
    let 类型 = 单调 > 线性 + 0.15 ? "非线性共振" : "线性吸引";
    let 方向 = 逆相关 ? "反向" : "正向";
    let 门槛信息 = null;
    if (线性 < 0.55 && 单调 < 0.55) {
      const 曲线 = this.二次拟合(a, b);
      if (曲线.决定系数 >= 0.65 && 曲线.峰值x !== null) {
        const x范围 = [Math.min(...a), Math.max(...a)];
        const 峰值有效 = 曲线.峰值x > x范围[0] + (x范围[1] - x范围[0]) * 0.15 &&
                       曲线.峰值x < x范围[1] - (x范围[1] - x范围[0]) * 0.15;
        if (峰值有效) {
          引力 = (曲线.决定系数 ** 1.1) * 质量因子 * (1 - 距离惩罚);
          类型 = "门槛建制";
          方向 = 曲线.开口方向 > 0 ? "先抑后扬" : "先扬后抑";
          const 峰值比例 = (曲线.峰值x - x范围[0]) / (x范围[1] - x范围[0]);
          门槛信息 = { 开口: 曲线.开口方向 > 0 ? "谷底" : "峰值", 位置比例: 峰值比例, 决定系数: 曲线.决定系数 };
        }
      }
    }
    return {
      引力: Math.min(Math.max(引力, 0), 1),
      线性,
      单调,
      方向,
      类型,
      门槛信息,
      共同样本,
      跳过: false,
    };
  }

  统计距离(质量甲, 质量乙) {
    const 缺失差 = Math.abs(质量甲.缺失率 - 质量乙.缺失率);
    const 规模甲 = Math.log10(Math.abs(质量甲.均值) + 1);
    const 规模乙 = Math.log10(Math.abs(质量乙.均值) + 1);
    const 规模差 = Math.min(Math.abs(规模甲 - 规模乙), 1);
    return Math.min(0.3 * 缺失差 + 0.2 * 规模差, 0.5);
  }

  分析(表格) {
    const 列数 = 表格.列名.length;
    const 列信息 = 表格.列名.map((名, j) => ({
      名称: 名,
      序列: 表格.数据[j],
      质量: this.计算列质量(表格.数据[j]),
    }));
    const 关系 = [];
    let 跳过对数 = 0;
    let 总对数 = 0;
    for (let i = 0; i < 列数; i++) {
      for (let j = i + 1; j < 列数; j++) {
        总对数++;
        const 关系结果 = this.计算引力(列信息[i], 列信息[j]);
        if (关系结果.跳过 || 关系结果.引力 < this.引力阈值) { 跳过对数++; continue; }
        关系.push({ 甲: 表格.列名[i], 乙: 表格.列名[j], ...关系结果 });
      }
    }
    关系.sort((x, y) => y.引力 - x.引力);
    const 跳过率 = 总对数 > 0 ? 跳过对数 / 总对数 : 0;
    return { 列信息, 关系, 总对数, 跳过对数, 跳过率 };
  }

  渲染关系图(分析结果, 表格) {
    const 图 = [];
    图.push("┌─ 数据引力场 · 关系图 ─────────────────────");
    图.push(`│ 数据规模: ${表格.行数} 行 × ${表格.列名.length} 个数值列（引力筛选阈值 ${this.引力阈值}）`);
    图.push(`│ 引力跳过率: ${(分析结果.跳过率 * 100).toFixed(1)}%（无语义关系的列对直接跳过，不进入解读）`);
    图.push("│");
    const 强关系 = 分析结果.关系.slice(0, 12);
    if (强关系.length === 0) {
      图.push("│ （未发现达到引力阈值的关系——各列在引力意义上相互独立）");
    }
    for (const 关系 of 强关系) {
      const 强度块 = Math.max(1, Math.round(关系.引力 * 10));
      const 条 = "█".repeat(强度块) + "░".repeat(10 - 强度块);
      const 箭头 = 关系.方向 === "正向" ? "⇄" : 关系.方向 === "反向" ? "⇆" : "↯";
      图.push(`│ ${关系.甲.padEnd(12, "　")} ${箭头} ${关系.乙.padEnd(12, "　")} ${条} ${关系.引力.toFixed(3)}`);
      const 类型注 = 关系.类型 === "门槛建制"
        ? `门槛建制（曲线拟合R²${关系.门槛信息.决定系数.toFixed(2)}，${关系.门槛信息.开口}在${关系.门槛信息.位置比例 <= 0.5 ? "前" : "后"}半段，共同样本${关系.共同样本}）`
        : `${关系.类型}（线性${关系.线性.toFixed(2)}/单调${关系.单调.toFixed(2)}，共同样本${关系.共同样本}）`;
      图.push(`│   └ ${类型注}`);
    }
    图.push("└──────────────────────────────────────────");
    return 图.join("\n");
  }

  人话解读(分析结果, 表格) {
    const 话 = [];
    话.push(`【一眼看懂】你的 ${表格.行数} 行数据里，我在 ${分析结果.总对数} 组列配对中锁定了 ${分析结果.关系.length} 组真实引力关系，其余 ${(分析结果.跳过率 * 100).toFixed(0)}% 属于「无语义关联」——就像引力判据筛选浮点数一样，我跳过了它们，保证你看到的每条关系都有意义。`);
    const 前三 = 分析结果.关系.slice(0, 3);
    前三.forEach((关系, 序号) => {
      const 序 = ["第一", "第二", "第三"][序号];
      if (关系.类型 === "门槛建制") {
        话.push(`${序}强的关系：${关系.甲} 和 ${关系.乙} 是门槛建制（引力${关系.引力.toFixed(2)}，曲线拟合度${(关系.门槛信息.决定系数 * 100).toFixed(0)}%）。它们不是「越多越好」，而是在${关系.门槛信息.位置比例 <= 0.5 ? "较早" : "较晚"}阶段出现${关系.门槛信息.开口}——过了这个点，关系${关系.门槛信息.开口 === "峰值" ? "开始反转下行" : "开始触底回升"}。这解释了为什么普通相关性分析看不出它们的关系。`);
      } else if (关系.类型 === "线性吸引") {
        话.push(`${序}强的关系：${关系.甲} 和 ${关系.乙} 呈${关系.方向}线性吸引（引力${关系.引力.toFixed(2)}）。一个升高，另一个${关系.方向 === "正向" ? "基本跟着升高" : "基本跟着下降"}，像绑在同一根绳上。适合直接互相预测。`);
      } else {
        话.push(`${序}强的关系：${关系.甲} 和 ${关系.乙} 是非线性共振（引力${关系.引力.toFixed(2)}）。它们同步起落但不成正比——可能存在「某个点之后才生效」的门槛效应，别用直线预测，分段看更准。`);
      }
    });
    if (前三.length > 0) {
      const 最强 = 前三[0];
      if (最强.类型 === "门槛建制") {
        话.push(`【建议动作】「${最强.甲} ↔ ${最强.乙}」存在最优点：把 ${最强.甲} 控制在数据范围的 ${Math.round(最强.门槛信息.位置比例 * 100)}% 附近（${最强.门槛信息.开口}位置），收益最高；越过它会${最强.门槛信息.开口 === "峰值" ? "不增反降" : "掉回谷底"}。别再线性加码了。`);
      } else {
        话.push(`【建议动作】优先围绕「${最强.甲} ↔ ${最强.乙}」做决策：调一个看另一个的响应；其余弱引力关系先放一边，噪声大于信息。`);
      }
    } else {
      话.push(`【建议动作】这份数据各列高度独立，别急着找规律——先确认数据是否来自同一批样本，或补充更多行数再试。`);
    }
    return 话.join("\n\n");
  }

  完整分析(CSV文本, 选项 = {}) {
    const 表格 = this.解析CSV(CSV文本);
    const 分析结果 = this.分析(表格);
    return {
      关系图: this.渲染关系图(分析结果, 表格),
      解读: this.人话解读(分析结果, 表格),
      原始关系: 分析结果.关系,
      跳过率: 分析结果.跳过率,
      列摘要: 分析结果.列信息.map(c => ({ 名称: c.名称, 均值: c.质量.均值, 标准差: c.质量.标准差, 缺失率: c.质量.缺失率 })),
    };
  }
}

